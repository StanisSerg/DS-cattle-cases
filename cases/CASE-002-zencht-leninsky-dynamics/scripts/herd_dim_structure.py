    dd = date.fromisoformat(d_iso)
    cows = [r for r in records if r[0] == dd and r[1] == g and r[2] != "" and r[5] is not None and r[5] > 0]
    if not cows:
        return None
    return (len(cows), sum(r[5] for r in cows) / len(cows), sum(r[3] for r in cows) / len(cows))

